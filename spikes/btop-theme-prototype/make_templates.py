#!/usr/bin/env python3
"""Emit the three candidate btop theme templates.

Each template is fully SELF-CONTAINED -- CSG's TemplateCatalogService treats
any extra *.j2 in the templates dir as a format to validate, so a shared
partial is not possible.

Structural rule enforced here: every emitted line begins at column 0.
btop's theme parser only treats '#' as a comment at offset 0 and otherwise
mangles lines with leading whitespace before '['.

Three profiles, a difficulty dial:
  csg-minimal  : every gradient is a slice of the wallpaper luminance ramp
  csg-balanced : + temp and cached(power) forced cool->warm
  csg-full     : + cpu forced cool->warm (6 call sites: GPU, cores, battery)
"""
from __future__ import annotations

import sys
from pathlib import Path

HERE = Path(__file__).parent

HEADER = """# btop theme generated by color-scheme-generator -- {title}
# source-image: {{{{ source_image }}}}
# backend: {{{{ backend }}}}
# generated-at: {{{{ generated_at }}}}
# variant: {slug} ({blurb})
#
# Palette note: colors[] is sorted by luminance, NOT by ANSI index.
# u[] below refers to the distinct (deduplicated) ramp stops.
"""

# --- semantic bases, identical across all three variants -------------------
BASE = [
    ("main_bg", "{{ background.hex }}"),
    ("main_fg", "{{ foreground.hex }}"),
    ("title", "{{ foreground.hex }}"),
    ("hi_fg", "{{ uniq[6].hex }}"),
    ("selected_bg", "{{ uniq[3].hex }}"),
    ("selected_fg", "{{ foreground.hex }}"),
    ("inactive_fg", "{{ uniq[2].hex }}"),
    ("graph_text", "{{ uniq[6].hex }}"),
    ("meter_bg", "{{ uniq[1].hex }}"),
    ("proc_misc", "{{ uniq[6].hex }}"),
    # neutral outlines: all four boxes + divider share one dim ramp stop
    ("cpu_box", "{{ uniq[2].hex }}"),
    ("mem_box", "{{ uniq[2].hex }}"),
    ("net_box", "{{ uniq[2].hex }}"),
    ("proc_box", "{{ uniq[2].hex }}"),
    ("div_line", "{{ uniq[1].hex }}"),
]

# process-state keys (added in btop 1.4.6)
STATE = [
    ("proc_pause_bg", "{{ uniq[5].hex }}"),
    ("proc_follow_bg", "{{ uniq[6].hex }}"),
    ("proc_banner_bg", "{{ uniq[3].hex }}"),
    ("proc_banner_fg", "{{ foreground.hex }}"),
    ("followed_bg", "{{ uniq[6].hex }}"),
    ("followed_fg", "{{ foreground.hex }}"),
]

# --- gradients --------------------------------------------------------------
# ramp:  (start, mid, end) as u[] indices into the luminance ramp
# sem:   forced cool->warm; COOL/MID/HOT are u[] indices
# "" mid => 2-stop gradient (btop's documented idiom)

RAMP = {
    "temp": (2, 5, 8),
    "cpu": (1, 4, 7),
    "free": (0, 3, 6),
    "cached": (1, 4, 7),
    "available": (0, 3, 6),
    "used": (1, 4, 7),
    "download": (0, 3, 6),
    "upload": (0, 3, 6),
    "process": (1, 4, 7),
}

# cool->warm stops present in this palette (blue -> terracotta -> gold)
COOL, MID, HOT = 3, 5, 7

# two-stop where the ramp direction is ambiguous (net throughput has no
# "more is brighter" reading) -- exercises the x_mid="" idiom
TWOSTOP = {"download", "upload"}

ORDER = ["temp", "cpu", "free", "cached", "available", "used", "download", "upload", "process"]

PROFILES = {
    "minimal": ("csg-minimal", "all gradients are wallpaper luminance slices", set()),
    "balanced": (
        "csg-balanced",
        "temp + power(forced cool->warm) over wallpaper ramp",
        {"temp", "cached"},
    ),
    "full": (
        "csg-full",
        "temp + power + cpu(forced cool->warm) over wallpaper ramp",
        {"temp", "cached", "cpu"},
    ),
}


def render_variant(slug: str, blurb: str, semantic: set[str]) -> str:
    out = [HEADER.format(title=slug, slug=slug, blurb=blurb)]

    out.append("\n# -- base surface colors " + "-" * 44)
    for key, val in BASE:
        out.append(f'theme[{key}]="{val}"')

    out.append("\n# -- process-state colors (btop >= 1.4.6) " + "-" * 29)
    for key, val in STATE:
        out.append(f'theme[{key}]="{val}"')

    out.append("\n# -- gradients " + "-" * 59)
    for name in ORDER:
        if name in semantic:
            kind = "SEMANTIC cool->warm"
            stops = (COOL, MID, HOT)
        else:
            kind = "ramp"
            stops = RAMP[name]
        out.append(f"\n# {name}: {kind}")
        for suffix, idx in zip(("start", "mid", "end"), stops):
            if suffix == "mid" and name in TWOSTOP and name not in semantic:
                out.append(f'theme[{name}_mid]=""')
            else:
                out.append(f'theme[{name}_{suffix}]="{{{{ uniq[{idx}].hex }}}}"')

    return "\n".join(out) + "\n"


def main() -> int:
    for key, (slug, blurb, semantic) in PROFILES.items():
        name = f"colors.btop-{key}.theme.j2"
        (HERE / name).write_text(render_variant(slug, blurb, semantic))
        print(f"wrote {name}  semantic={sorted(semantic) or 'none'}")
    return 0


if __name__ == "__main__":
    sys.exit(main())
