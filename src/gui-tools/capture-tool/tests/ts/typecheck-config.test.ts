// ---------------------------------------------------------------------------
// Typecheck CONFIG tests (harden-capture-typecheck-config).
//
// THE DEFECT THESE PIN. `tsconfig.capture.json` declared neither `"types"` nor
// `"typeRoots"`. With both absent, TypeScript's default typeRoots walk takes
// every `node_modules/@types` from the config's own directory upwards and
// auto-includes ALL of it. So the APP's ambient-type surface was not a property
// of the app — it was a property of where a directory happened to sit on disk.
//
// The app is GJS, not Node: no `process`, no `Buffer`, no `require`. It should
// have an EMPTY ambient-type surface. It got one by accident: `@types/node`
// lives at `tests/node_modules/`, which the upward walk never descends into.
// That is luck, not design, and `git mv` away from luck.
//
// WHAT IS ACTUALLY ASSERTED HERE, and why it is a real assertion rather than a
// comment:
//
//   1. The app config PINS the surface explicitly: `compilerOptions.types` is
//      present AND is the empty array. Removing the pin, or renaming it to
//      `["node"]`, fails these tests immediately — they do not depend on
//      whether TypeScript happens to be installed.
//   2. The tests config still ASKS for node by name. This is the half that
//      could regress the other way: pinning the app must not have been
//      achieved by deleting node types from the world. The domain unit tests
//      genuinely need `node:test` and `node:assert`.
//   3. REAL COMPILER EVIDENCE: run the actual `tsc --noEmit --listFiles` over
//      the app project and assert that ZERO files from `@types/node` are in the
//      program, PLUS a positive control running the identical measurement over
//      the tests config, which MUST find them. Without the control the assertion
//      is unfalsifiable — an absent package and a correct exclusion look
//      identical. The control also pins the @types/node install this gate
//      declares.
//
//      This case DOES NOT SKIP. It used to, with a printed NOTE, whenever
//      TypeScript was unresolvable — which on a clean checkout it always was,
//      because nothing installed @types/node for the `"types": ["node"]` in
//      tsconfig.tests.json. That is a dependency gap, not an environment
//      condition, and hiding it in a skip meant the gate reported 114/1 instead
//      of 115/0 while its own tsc pass could not run at all. `make capture-test`
//      now declares and installs both (its `capture-test-deps` target), so an
//      unresolvable tsc inside this gate is a real failure and is reported as
//      one, with the fix named in the message.
//
// On (3): `--listFiles` is the direct measurement of "what ambient types did
// this config actually admit", which is the property under test. Asserting it
// against `tsc` rather than re-deriving typeRoots resolution in JS avoids
// reimplementing the very walk whose behaviour is in question.
//
// SCOPE, and why the FULL app program is not asserted here: the app typechecks
// against @girs/ — 168 machine-specific .d.ts files generated by `ags types`
// from THIS host's GTK/Astal. A CI runner has none, and 344 errors there are all
// unresolved `ags/*` and `gi://*` specifiers rather than defects. Asserting the
// whole program would make this case desktop-only, which is `make
// capture-typecheck`'s job and which asserts the same property STRICTLY harder:
// it fails on any error under src/gui-tools/capture-tool/ *and* on any error in
// neither the capture tool nor the known ags runtime. What this case owns is the
// ambient-type surface, so that is what it measures, over the desktop-free layer
// (`domain/`, `ports/`, `types.ts` — measured 0 errors with and without @girs)
// plus the leak itself.
// ---------------------------------------------------------------------------

import { test } from "node:test"
import assert from "node:assert/strict"
import { readFileSync, existsSync } from "node:fs"
import { spawnSync } from "node:child_process"
import { fileURLToPath } from "node:url"
import { dirname, resolve } from "node:path"

const HERE = dirname(fileURLToPath(import.meta.url))
const CAPTURE_TOOL = resolve(HERE, "../..")
const APP_CONFIG = resolve(CAPTURE_TOOL, "tsconfig.capture.json")
const TESTS_CONFIG = resolve(CAPTURE_TOOL, "tests/tsconfig.tests.json")
const REPO_ROOT = resolve(CAPTURE_TOOL, "../../..")

// The configs are JSONC (they carry a "//" rationale block and inline
// comments). Strip comments while respecting string literals — the top-level
// `"//"` KEY is itself a string containing slashes, so a naive regex strip
// would eat the file.
function parseJsonc(path: string): any {
  const raw = readFileSync(path, "utf8")
  let out = ""
  let inString = false
  let escaped = false
  for (let i = 0; i < raw.length; i++) {
    const ch = raw[i]
    if (inString) {
      out += ch
      if (escaped) escaped = false
      else if (ch === "\\") escaped = true
      else if (ch === '"') inString = false
      continue
    }
    if (ch === '"') {
      inString = true
      out += ch
      continue
    }
    if (ch === "/" && raw[i + 1] === "/") {
      while (i < raw.length && raw[i] !== "\n") i++
      out += "\n"
      continue
    }
    if (ch === "/" && raw[i + 1] === "*") {
      i += 2
      while (i < raw.length && !(raw[i] === "*" && raw[i + 1] === "/")) i++
      i++
      continue
    }
    out += ch
  }
  return JSON.parse(out)
}

const appConfig = parseJsonc(APP_CONFIG)
const appOptions = appConfig.compilerOptions ?? {}

test("app config pins its ambient-type surface to empty", () => {
  // The core regression assertion. Absent `"types"`, the surface is whatever
  // the typeRoots walk happens to find, which is not a property of the app.
  assert.ok(
    Object.prototype.hasOwnProperty.call(appOptions, "types"),
    "tsconfig.capture.json must declare compilerOptions.types explicitly; " +
      "omitting it makes the app's ambient types depend on directory layout",
  )
  assert.deepEqual(
    appOptions.types,
    [],
    "the GJS app must have an EMPTY ambient-type surface: it has no process, " +
      "no Buffer and no require. If a type genuinely belongs here, add it by " +
      "name and re-justify it — do not reopen the walk.",
  )
})

test("app config does not name node, and does not widen typeRoots", () => {
  const types = appOptions.types as unknown[]
  assert.ok(
    !types.includes("node"),
    "the capture app runs under GJS, not Node; @types/node must not be ambient in it",
  )
  // `typeRoots` is the other half of the surface. A typeRoots pointing at a
  // shared node_modules would reintroduce the same layout dependence that
  // `"types": []` exists to remove, so it must stay unset.
  assert.ok(
    !Object.prototype.hasOwnProperty.call(appOptions, "typeRoots"),
    "tsconfig.capture.json must not set typeRoots; the empty `types` list is " +
      "what pins the surface, and a typeRoots would reopen the walk",
  )
})

test("tests config still asks for node types by name", () => {
  // The other half of the change. Pinning the app must not have been achieved
  // by taking node types away from the tests, which genuinely need node:test.
  const testsOptions = parseJsonc(TESTS_CONFIG).compilerOptions ?? {}
  assert.ok(
    Array.isArray(testsOptions.types) && testsOptions.types.includes("node"),
    "tsconfig.tests.json must keep `\"types\": [\"node\"]`; the domain unit " +
      "tests import node:test and node:assert",
  )
})

test("app program contains no @types/node files (real compiler evidence)", () => {
  // The compiler is a DECLARED dependency of this gate now (see
  // `capture-test-deps` in the Makefile), so its absence is a broken gate, not
  // an unsupported environment. Failing here — loudly, with the fix — is the
  // whole point: the previous `t.skip` made a clean checkout look green at
  // 114/1 while the one assertion that measures the real compiler never ran.
  const tsc = [
    resolve(REPO_ROOT, "node_modules/.bin/tsc"),
    resolve(CAPTURE_TOOL, "node_modules/.bin/tsc"),
  ].find((p) => existsSync(p))

  assert.ok(
    tsc,
    "tsc is not resolvable at node_modules/.bin/tsc, so the compiler-evidence " +
      "check cannot run. Run `make capture-test`, which installs typescript and " +
      "@types/node on demand (capture-test-deps). This gate does not skip when a " +
      "declared dependency is missing.",
  )

  const res = spawnSync(tsc, ["--noEmit", "-p", APP_CONFIG, "--listFiles"], {
    encoding: "utf8",
  })
  // And the compile must have actually run rather than bailing early.
  assert.ok(
    res.status === 0 || res.status === 2,
    `tsc exited ${res.status}, which is neither success (0) nor the tolerated ` +
      `error status (2):\n${res.stderr}`,
  )

  const programFiles = res.stdout.split("\n")
  const nodeTypeFiles = programFiles.filter((f) => /@types[\\/]node[\\/]/.test(f))

  // This is the assertion the original defect fails. @types/node is installed at
  // tests/node_modules/ — below the app config's own directory, so the default
  // typeRoots walk never reaches it — and the config pins `"types": []`, so it
  // is not in the program. Two independent guards, both measured.
  assert.deepEqual(
    nodeTypeFiles,
    [],
    `@types/node leaked into the GJS app program (${nodeTypeFiles.length} files). ` +
      `The app's ambient-type surface must stay empty regardless of where ` +
      `@types/node is installed on disk.`,
  )

  // POSITIVE CONTROL, and the anti-vacuity guard this case most needs.
  //
  // The assertion above proves nothing unless the same compiler, the same
  // invocation and the same regex CAN see @types/node when it is admitted. So
  // run the identical measurement against the tests config, which asks for
  // `"types": ["node"]` by name, and require that it DOES find it.
  //
  // This is strictly stronger than the old "program has >10 files" sanity
  // check: a program of any size passes if @types/node is genuinely absent
  // from the app, and fails if the regex or the typeRoots walk is not what we
  // think it is. It also pins the DEPENDENCY this change installed — if
  // @types/node goes missing again, the positive control fails here with a
  // precise cause instead of the app check passing vacuously.
  const testsRes = spawnSync(
    tsc,
    ["--noEmit", "-p", TESTS_CONFIG, "--listFiles"],
    { encoding: "utf8" },
  )
  assert.ok(
    testsRes.status === 0,
    `the tests project must typecheck cleanly — it declares "types": ["node"] ` +
      `and make capture-test installs @types/node for it — but tsc exited ` +
      `${testsRes.status}:\n${testsRes.stdout}\n${testsRes.stderr}`,
  )
  const testsNodeTypeFiles = testsRes.stdout
    .split("\n")
    .filter((f) => /@types[\\/]node[\\/]/.test(f))
  assert.ok(
    testsNodeTypeFiles.length > 0,
    "the tests program contains no @types/node files, so the app-project check " +
      "above cannot distinguish 'Node types correctly excluded from the GJS app' " +
      "from 'the measurement cannot see @types/node at all'. " +
      "Run `make capture-test`, which installs @types/node under " +
      "src/gui-tools/capture-tool/tests/.",
  )

  // The DESKTOP-FREE part of the app must typecheck clean under the app's own
  // config. This is the subset this gate can honestly judge: `domain/`, `ports/`
  // and `types.ts` import nothing from `ags/*` or `gi://*`, so they resolve with
  // or without the generated @girs/ closure. Measured 0 both ways.
  //
  // The FULL app program needs @girs/ (168 machine-specific .d.ts files from
  // `ags types`), which a CI runner does not have — 344 errors there are all
  // unresolved `ags/`+`gi://` specifiers, not defects. Asserting the whole
  // program here would make this case desktop-only, which is capture-typecheck's
  // job and which asserts this strictly more strongly anyway: it fails on any
  // error under src/gui-tools/capture-tool/ AND on any error in neither the
  // capture tool nor the known ags runtime. See the `capture-typecheck` target.
  const errorLines = (res.stdout + res.stderr)
    .split("\n")
    .filter((l) => l.includes("error TS"))
  const oursInDesktopFree = errorLines.filter((l) =>
    /src\/gui-tools\/capture-tool\/(domain|ports)\/|src\/gui-tools\/capture-tool\/types\.ts/.test(l),
  )
  assert.deepEqual(
    oursInDesktopFree,
    [],
    `the app's desktop-free layer (domain/, ports/, types.ts) must typecheck ` +
      `with 0 errors under tsconfig.capture.json, but tsc reported ` +
      `${oursInDesktopFree.length}:\n${oursInDesktopFree.join("\n")}`,
  )
})
